import 'tts_text.dart';

/// English names for locale tags, for picking a TTS voice by language and
/// region: `zh-TW` → `Chinese (Taiwan)`. Covers the languages and regions TTS
/// engines commonly offer; an unknown subtag is shown as its code.
class LocaleNames {
  LocaleNames._();

  /// The name of [tag]: its language, then its script and region in
  /// brackets (`Chinese (Traditional, Taiwan)`).
  static String of(String tag) {
    final parts = TtsText.normalizeLocale(tag).split('-');
    final language = _languages[parts.first] ?? parts.first;
    final details = [
      for (final part in parts.skip(1))
        part.length == 4 ? (_scripts[part] ?? part) : (_regions[part] ?? part),
    ];
    return details.isEmpty ? language : '$language (${details.join(', ')})';
  }

  /// Whether [code] is a known language (`zh`, `yue`), in any case.
  static bool isLanguage(String code) =>
      _languages.containsKey(code.toLowerCase());

